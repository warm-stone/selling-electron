/**
 * RAW 编码探针（F1）——共享层：段标签与判读指引。
 *
 * 为什么需要探针：spooler 通道走 `winspool.WritePrinter(pDataType='RAW')`，字节
 * **完全绕开打印机驱动**，由固件自己解释。所以「Word 里能打中文」证明不了 RAW
 * 能打中文——Word 走 GDI → 驱动光栅化，那正是 driver 通道。真机（得力 DL-5801PW）
 * 的表现是「英文可打、中文与 Logo 不出」，一度被解读为「固件按纯文本渲染而非
 * ESC/POS」——**20261118 探针实证该解读是错的**：S4 `GS v 0` 光栅黑块正常出图
 * （指令层完好），S2/S3 的中文不出且空白格数 ≈ 高位字节数 → 真因是**固件无
 * CJK 字模**（对每个 ≥0x80 字节「吃掉 + 推进半角空位 + 不画点」，与编码、与
 * 汉字模式无关）。结论详见 docs/windows-manual-checklist.md §11.3 回填。
 *
 * 探针把八种固件能力假设排在同一张纸上一次打完（S1–S4 = v1 编码矩阵对角线 +
 * 光栅基线；S5–S8 = v2 补齐「汉字模式 × 编码」矩阵、单字节高位出墨验证、光栅尺寸
 * 阶梯），纸上结果直接决定 spooler 通道的修法，不必逐次改代码重试。段标签是纸上
 * 真正打印的 ASCII 文字（照纸找段），主进程 builder 与渲染层判读表共用这一份常量
 * ——标签改了判读表不会失配。
 */

